-- DRAFT, not applied. Public CMS/HHS reference data used by the deterministic rules.
--
-- These tables are shared and contain no user data, so there is no user_id and
-- no per-user RLS (see CLAUDE.md rule 4). Instead: RLS on, SELECT for
-- authenticated only, and no insert/update/delete policies at all. Writes happen
-- only through the service role (import scripts), which bypasses RLS.
--
-- Conventions:
--   * Codes and locality numbers are text (leading zeros matter).
--   * Money is integer cents (*_cents).
--   * Non-money decimals with a fixed number of places are stored as scaled
--     integers so the rules never touch floats:
--       RVUs  -> hundredths  (1.46  -> 146)   *_rvu_x100
--       GPCIs -> thousandths (0.988 -> 988)   *_gpci_x1000
--       CF    -> ten-thousandths of a dollar (33.4009 -> 334009)  *conversion_factor_x10000
--   * source_release identifies the file/release a row came from, e.g.
--     'NCCI-2026Q4', 'NCCI-MUE-2026Q4', 'RVU26A', 'HHS-2026'.

-- ---------------------------------------------------------------------------
-- NCCI procedure-to-procedure edits
-- ---------------------------------------------------------------------------
-- The file has 12 distinct rationale strings. They live in a lookup table so the
-- ~1.76M edit rows carry a 2-byte id instead of ~43 bytes of text. The import
-- script upserts the strings by text and then maps each edit to its id.
create table ncci_ptp_rationale (
  id smallint generated by default as identity primary key,
  rationale text not null unique,
  source_release text not null
);

-- Import filter: modifier indicator 0 or 1 only (9 = not applicable is skipped)
-- and deletion_date null or >= 2024-01-01. The file's '*' deletion date => NULL.
create table ncci_ptp (
  -- Which PTP edit file the row came from: 1 = practitioner, 2 = hospital outpatient.
  -- The same code pair can have different edits in each set.
  edit_set smallint not null default 1 check (edit_set in (1, 2)),
  column1_code text not null check (length(column1_code) = 5),
  column2_code text not null check (length(column2_code) = 5),
  effective_date date not null,
  deletion_date date,
  modifier_indicator smallint not null check (modifier_indicator in (0, 1)),
  rationale_id smallint not null references ncci_ptp_rationale (id),
  source_release text not null,
  primary key (edit_set, column1_code, column2_code, effective_date),
  check (deletion_date is null or deletion_date >= effective_date)
);

-- The primary key covers lookups by edit_set + column1_code (and + column2).
-- This covers lookups by edit_set + column2_code (and + column1).
create index ncci_ptp_column2_idx on ncci_ptp (edit_set, column2_code, column1_code);

-- ---------------------------------------------------------------------------
-- NCCI medically unlikely edits
-- ---------------------------------------------------------------------------
-- The file's adjudication field is one string like '2 Date of Service Edit: Policy';
-- it is split into the leading digit and the remaining text.
create table ncci_mue (
  code text not null check (length(code) = 5),
  service_type text not null default 'practitioner'
    check (service_type in ('practitioner', 'outpatient', 'dme')),
  mue_value integer not null check (mue_value >= 0),
  adjudication_indicator smallint not null check (adjudication_indicator in (1, 2, 3)),
  adjudication_text text not null,
  rationale text not null,
  source_release text not null,
  primary key (code, service_type)
);

-- ---------------------------------------------------------------------------
-- Medicare Physician Fee Schedule RVUs (one row per code + modifier)
-- ---------------------------------------------------------------------------
-- Stores components, not a price. See the price formula in the notes below.
-- The 2026 release ships as two files (non-QPP and QPP) whose RVU components are
-- identical for every shared code; only the conversion factor differs. So there
-- is one row per code with both factors:
--   conversion_factor_x10000      non-QPP factor (33.4009 for 2026), always present
--   qpp_conversion_factor_x10000  QPP factor (33.5675 for 2026); NULL when the code
--                                 is not in the QPP file (what to do then is a
--                                 rules decision, not a data one)
create table mpfs_rates (
  hcpcs_code text not null check (length(hcpcs_code) = 5),
  modifier text not null default '' check (modifier in ('', '26', 'TC', '53')),
  status_code text not null,
  work_rvu_x100 integer not null,
  nonfacility_pe_rvu_x100 integer not null,
  facility_pe_rvu_x100 integer not null,
  malpractice_rvu_x100 integer not null,
  nonfacility_pe_na boolean not null default false,
  facility_pe_na boolean not null default false,
  conversion_factor_x10000 integer not null check (conversion_factor_x10000 > 0),
  qpp_conversion_factor_x10000 integer check (qpp_conversion_factor_x10000 > 0),
  pctc_indicator text,
  global_days text,
  mult_proc_indicator text,
  bilat_surg_indicator text,
  asst_surg_indicator text,
  co_surg_indicator text,
  team_surg_indicator text,
  source_release text not null,
  primary key (hcpcs_code, modifier)
);

-- ---------------------------------------------------------------------------
-- Geographic practice cost indices (one row per MAC + locality)
-- ---------------------------------------------------------------------------
-- Both work GPCI columns are stored as published. Rules should use
-- work_gpci_nofloor_x1000: the 1.0 work floor is a temporary statutory
-- provision, so the no-floor value is the one that persists.
create table gpci (
  mac_code text not null,
  locality_number text not null,
  state_code text not null check (length(state_code) = 2),
  locality_name text not null,
  work_gpci_nofloor_x1000 integer not null,  -- rules use this one
  work_gpci_floor_x1000 integer not null,    -- as published with the 1.0 floor; kept for reference only
  pe_gpci_x1000 integer not null,
  mp_gpci_x1000 integer not null,
  source_release text not null,
  primary key (mac_code, locality_number)
);

create index gpci_state_idx on gpci (state_code, locality_number);

-- ---------------------------------------------------------------------------
-- HHS federal poverty guidelines
-- ---------------------------------------------------------------------------
-- Intentionally empty: the import script fills it from the published tables.
-- Download the 2026 guidelines from the HHS ASPE poverty guidelines page,
-- https://aspe.hhs.gov/topics/poverty-economic-mobility/poverty-guidelines
-- (the same figures appear in the Federal Register notice each January).
-- Sizes 1-8 are listed; larger households = size-8 line + (n - 8) * increment.
create table poverty_guidelines (
  guideline_year smallint not null,
  region text not null check (region in ('contiguous', 'AK', 'HI')),
  household_size smallint not null check (household_size between 1 and 8),
  poverty_line_cents bigint not null check (poverty_line_cents > 0),
  per_additional_person_cents bigint not null check (per_additional_person_cents > 0),
  source_release text not null,
  primary key (guideline_year, region, household_size)
);

-- ---------------------------------------------------------------------------
-- RLS: read-only for signed-in users; no write policies.
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'ncci_ptp_rationale', 'ncci_ptp', 'ncci_mue', 'mpfs_rates', 'gpci', 'poverty_guidelines'
  ]
  loop
    execute format('alter table %I enable row level security', t);
    execute format(
      'create policy %I on %I for select to authenticated using (true)',
      t || '_select_authenticated', t
    );
    -- Supabase grants write privileges to authenticated by default; remove them
    -- so the absence of write policies is backed by missing grants too.
    execute format('revoke insert, update, delete, truncate on %I from anon, authenticated', t);
    execute format('revoke select on %I from anon', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Notes: MPFS price formula (applied in src/lib/rules, in integer math)
-- ---------------------------------------------------------------------------
--   pe_rvu = facility ? facility_pe_rvu : nonfacility_pe_rvu   (by place of service)
--   price  = (work_rvu * work_gpci + pe_rvu * pe_gpci + mp_rvu * mp_gpci) * conversion_factor
--   with work_gpci = work_gpci_nofloor
--
-- With the scaled integers:
--   s           = work_x100 * work_gpci_x1000
--               + pe_x100   * pe_gpci_x1000
--               + mp_x100   * mp_gpci_x1000          -- units: 1e-5 RVU
--   price_cents = round_half_up(s * conversion_factor_x10000 / 1e7)
--
-- Max s is about 1e8 and the CF about 3.4e5, so the product (~3e13) fits exactly
-- in a JS number; no floats are involved.
